export function getIcon(name) {
  return icons[name];
}

/** Desenha o ícone pelo nome; não desenha nada se o nome não existir. */
export function ContentIcon({ name, ...props }) {
  const icon = icons[name];
  return icon ? createElement(icon, props) : null;
}
